#!/usr/bin/env python3
#
# make_rcssmonitor_svg.py -- create the application icon icons/app/svg/rcssmonitor.svg
#
# Usage: python3 icons/app/make_rcssmonitor_svg.py
#        icons/generate.sh rcssmonitor
#
# The icon is a display showing the official RoboCup logo, on the 32x32
# grid: a thin black bezel with a thin silver rim (seen on a dark background
# too), on a gray pole and a round foot. The logo is the PNG file robocup_logo.png
# next to this script, embedded in the SVG file as a data URI, unmodified.
# The screen has the aspect ratio of the logo. Only the standard library of
# Python 3 is used. generate.sh then creates the PNG files of the sizes
# (icons/app/SIZE/rcssmonitor.png). See docs/plan/2026-11-22-01_icon-redesign.md.
#
# robocup_logo.png is the logo's part (the gray box with the green band,
# 397x252 pixels from (175, 38)) of the image of the RoboCup Federation
#   https://www.robocup.org/system/static_contents/images/000/000/010/list/robocup_logo_ext.jpg
# (750x330, JPEG; no vector or larger version is offered on
# https://robocup.org/logo_guidelines as of 2026-11-22), cut out unmodified
# and saved as PNG, e.g. with Pillow:
#   python3 -c "from PIL import Image; Image.open('robocup_logo_ext.jpg').convert('RGB').crop((175, 38, 572, 290)).save('robocup_logo.png', optimize=True)"

import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LOGO = os.path.join(HERE, 'robocup_logo.png')
OUT = os.path.join(HERE, 'svg', 'rcssmonitor.svg')

# the screen (the logo) and the frame around it, on the 32x32 grid
SCREEN_WIDTH = 27.0
BEZEL = 0.8  # the black bezel around the screen
RIM = 0.3  # the silver rim around the bezel
RIM_OUTLINE = 0.25  # the gray outline of the rim (seen on a light background)
BEZEL_RADIUS = 0.9
POLE_WIDTH = 2.0
POLE_HEIGHT = 4.4
FOOT_RX = 7.0
FOOT_RY = 1.3
FOOT_CENTER = 4.6  # from the display's bottom to the foot's center

BEZEL_COLOR = '#111214'
RIM_TOP = '#f2f4f6'  # the silver: a vertical gradient
RIM_BOTTOM = '#bfc4cb'
RIM_EDGE = '#8a919b'
POLE_COLOR = '#8a9099'
FOOT_COLOR = '#5f656e'


def png_size(path):
    """the width and the height of a PNG file (from its IHDR chunk)"""
    with open(path, 'rb') as f:
        head = f.read(24)
    if head[:8] != b'\x89PNG\r\n\x1a\n' or head[12:16] != b'IHDR':
        sys.exit('make_rcssmonitor_svg.py: %s is not a PNG file' % path)
    return struct.unpack('>II', head[16:24])


def num(v):
    """a number for SVG: at most 2 decimals, no trailing zeros"""
    return ('%.2f' % v).rstrip('0').rstrip('.')


def main():
    width, height = png_size(LOGO)
    with open(LOGO, 'rb') as f:
        data = base64.b64encode(f.read()).decode('ascii')

    screen_height = SCREEN_WIDTH * height / width
    screen_x = (32.0 - SCREEN_WIDTH) / 2
    # the display (the rim's outside), centered vertically with the stand
    frame = BEZEL + RIM
    display_width = SCREEN_WIDTH + 2 * frame
    display_height = screen_height + 2 * frame
    display_x = screen_x - frame
    display_y = (32.0 - (display_height + FOOT_CENTER + FOOT_RY)) / 2
    bottom = display_y + display_height

    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="32" height="32" viewBox="0 0 32 32">
  <!-- rcssmonitor: a display showing the official RoboCup logo (robocup_logo.png, unmodified).
       Generated by make_rcssmonitor_svg.py. Do not edit. -->
  <defs>
    <linearGradient id="silver" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{RIM_TOP}"/>
      <stop offset="1" stop-color="{RIM_BOTTOM}"/>
    </linearGradient>
  </defs>
  <rect x="{num(16 - POLE_WIDTH / 2)}" y="{num(bottom - 0.3)}" width="{num(POLE_WIDTH)}" height="{num(POLE_HEIGHT)}" fill="{POLE_COLOR}"/>
  <ellipse cx="16" cy="{num(bottom + FOOT_CENTER)}" rx="{num(FOOT_RX)}" ry="{num(FOOT_RY)}" fill="{FOOT_COLOR}"/>
  <rect x="{num(display_x)}" y="{num(display_y)}" width="{num(display_width)}" height="{num(display_height)}" rx="{num(BEZEL_RADIUS + RIM)}" fill="url(#silver)" stroke="{RIM_EDGE}" stroke-width="{num(RIM_OUTLINE)}"/>
  <rect x="{num(display_x + RIM)}" y="{num(display_y + RIM)}" width="{num(SCREEN_WIDTH + 2 * BEZEL)}" height="{num(screen_height + 2 * BEZEL)}" rx="{num(BEZEL_RADIUS)}" fill="{BEZEL_COLOR}"/>
  <image x="{num(screen_x)}" y="{num(display_y + frame)}" width="{num(SCREEN_WIDTH)}" height="{num(screen_height)}" preserveAspectRatio="none" xlink:href="data:image/png;base64,{data}"/>
</svg>
'''
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write(svg)
    print('created %s (the logo %dx%d)' % (os.path.relpath(OUT), width, height))


if __name__ == '__main__':
    main()
