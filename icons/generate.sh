#!/bin/sh
#
# generate.sh -- create the PNG files of the icons from the SVG files
#
# Usage: icons/generate.sh [NAME...]
#        icons/generate.sh --lists
#
# For each icon NAME (svg/NAME.svg), the following PNG files are created
# with Inkscape (SIZE: 16, 24, 32 and 48):
#
#   light/SIZE/NAME.png   the colors of the SVG file
#   dark/SIZE/NAME.png    the colors replaced by palette.txt
#
# 24 and 48 are for the buttons drawn at 24 px (Live Mode and Play), on
# normal and HiDPI (device pixel ratio 2) displays.
#
# For each application icon NAME (app/svg/NAME.svg), the PNG files
# app/SIZE/NAME.png are created for the sizes 16, 32, 48, 64, 128 and 256.
# If app/svg/NAME.SIZE.svg exists (e.g. app/svg/fedit2.16.svg), it is used
# for that size instead of app/svg/NAME.svg. The application icons are not
# switched by the color scheme, so they can use any colors.
#
# If no NAME is given, the PNG files of all the icons are created.
# Then the following files are updated:
#
#   icons.qrc          the Qt resource file (the list of the PNG files)
#   icons.am           the lists of the files for Automake
#   generated.sha256   the checksums of the SVG files and palette.txt
#                      (test/check_icons.sh uses it to detect the PNG files
#                      that are not created again after editing)
#
# --lists updates only icons.qrc and icons.am. Inkscape is not used.
#
# Environment variables:
#   INKSCAPE   the Inkscape command (default: inkscape).
#              It can have arguments, e.g. "flatpak run org.inkscape.Inkscape".
#
# The commands are printed before they are run. See docs/icons.md.

set -e

# the order of the files in the lists does not depend on the locale
LC_ALL=C
export LC_ALL

SIZES="16 24 32 48"
APP_SIZES="16 32 48 64 128 256"

# print the comment at the top of this file
usage()
{
    awk 'NR > 2 && /^#/ { sub( /^# ?/, "" ); print; next } NR > 2 { exit }' "$0"
}

die()
{
    echo "generate.sh: $*" >&2
    exit 1
}

# print a command
show()
{
    echo "+ $*"
}

# print the checksum of the files in the format of sha256sum
checksum()
{
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$@"
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$@"
    else
        die "sha256sum or shasum is required"
    fi
}

# print the names of all the icons (the SVG files in svg/)
all_names()
{
    for f in svg/*.svg; do
        [ -f "$f" ] || continue
        basename "$f" .svg
    done
}

# print the names of all the application icons (app/svg/NAME.svg)
all_app_names()
{
    for f in app/svg/*.svg; do
        [ -f "$f" ] || continue
        case "$(basename "$f" .svg)" in
            *.*) ;; # app/svg/NAME.SIZE.svg
            *) basename "$f" .svg ;;
        esac
    done
}

# print all the SVG files of the application icons (including NAME.SIZE.svg)
all_app_svg_files()
{
    for f in app/svg/*.svg; do
        [ -f "$f" ] && echo "$f"
    done
}

# app_source NAME SIZE
#   print the SVG file to create the application icon of the size
app_source()
{
    if [ -f "app/svg/$1.$2.svg" ]; then
        echo "app/svg/$1.$2.svg"
    else
        echo "app/svg/$1.svg"
    fi
}

# update icons.qrc and icons.am from the SVG files
update_lists()
{
    names=$(all_names)
    app_names=$(all_app_names)

    {
        echo '<!DOCTYPE RCC>'
        echo '<!-- Generated by generate.sh from the SVG files in svg/ and app/svg/. Do not edit. See docs/icons.md. -->'
        echo '<RCC version="1.0">'
        echo '<qresource prefix="/icons">'
        for name in $names; do
            for scheme in light dark; do
                for size in $SIZES; do
                    echo "    <file>$scheme/$size/$name.png</file>"
                done
            done
        done
        for name in $app_names; do
            for size in $APP_SIZES; do
                echo "    <file>app/$size/$name.png</file>"
            done
        done
        echo '</qresource>'
        echo '</RCC>'
    } > icons.qrc.tmp
    mv icons.qrc.tmp icons.qrc
    echo "updated icons.qrc"

    {
        echo '## Generated by generate.sh from the SVG files in svg/ and app/svg/. Do not edit.'
        echo '## Included by Makefile.am and src/Makefile.am, which set ICONS_DIR.'
        echo ''
        printf 'ICONS_SVG_FILES ='
        for name in $names; do
            printf ' \\\n\t$(ICONS_DIR)/svg/%s.svg' "$name"
        done
        for f in $(all_app_svg_files); do
            printf ' \\\n\t$(ICONS_DIR)/%s' "$f"
        done
        printf '\n\nICONS_PNG_FILES ='
        for name in $names; do
            for scheme in light dark; do
                for size in $SIZES; do
                    printf ' \\\n\t$(ICONS_DIR)/%s/%s/%s.png' "$scheme" "$size" "$name"
                done
            done
        done
        for name in $app_names; do
            for size in $APP_SIZES; do
                printf ' \\\n\t$(ICONS_DIR)/app/%s/%s.png' "$size" "$name"
            done
        done
        printf '\n'
    } > icons.am.tmp
    mv icons.am.tmp icons.am
    echo "updated icons.am"
}

# update generated.sha256 for the given icons
# (the lines of the other icons are kept as they are)
update_checksums()
{
    checksum palette.txt > generated.sha256.tmp
    for f in $(for name in $(all_names); do echo "svg/$name.svg"; done) $(all_app_svg_files); do
        # the name of the icon (svg/NAME.svg, app/svg/NAME.svg or app/svg/NAME.SIZE.svg)
        name=$(basename "$f" .svg | cut -d . -f 1)
        if echo " $* " | grep -q " $name "; then
            checksum "$f" >> generated.sha256.tmp
        elif [ -f generated.sha256 ]; then
            # the file name starts at the 67th column (64 digits and 2 spaces)
            awk -v f="$f" 'substr( $0, 67 ) == f' generated.sha256 >> generated.sha256.tmp
        fi
    done
    mv generated.sha256.tmp generated.sha256
    echo "updated generated.sha256"
}

# move to the directory of this script
cd "$(dirname "$0")"

case "${1:-}" in
    -h|--help)
        usage
        exit 0
        ;;
    --lists)
        update_lists
        exit 0
        ;;
    -*)
        usage >&2
        die "unknown option: $1"
        ;;
esac

awk -v mode=palette -f palette.awk palette.txt || die "errors in palette.txt"

# the icons to create (names: the icons in svg/, app_names: the application icons)
names=""
app_names=""
if [ $# -gt 0 ]; then
    for name in "$@"; do
        if [ -f "svg/$name.svg" ]; then
            names="$names $name"
        elif [ -f "app/svg/$name.svg" ]; then
            app_names="$app_names $name"
        else
            die "svg/$name.svg or app/svg/$name.svg does not exist"
        fi
    done
    # all the icons must be created again if palette.txt is changed
    if [ -f generated.sha256 ] \
           && ! grep -q "^$(checksum palette.txt | cut -d ' ' -f 1)  palette.txt\$" generated.sha256; then
        echo "palette.txt has been changed. All the icons in svg/ are created."
        names=$(all_names)
    fi
else
    names=$(all_names)
    app_names=$(all_app_names)
fi
[ -n "$names$app_names" ] || die "no SVG file in svg/ and app/svg/"

for name in $names $app_names; do
    case "$name" in
        *[!a-z0-9_]*) die "invalid icon name: $name (use only a-z, 0-9 and _)" ;;
    esac
done
for name in $(all_app_names); do
    [ ! -f "svg/$name.svg" ] || die "$name is used by both svg/ and app/svg/"
done
for f in $(all_app_svg_files); do
    case "$(basename "$f" .svg)" in
        *.*)
            base=$(basename "$f" .svg | cut -d . -f 1)
            size=$(basename "$f" .svg | cut -d . -f 2-)
            [ -f "app/svg/$base.svg" ] || die "$f: app/svg/$base.svg does not exist"
            echo " $APP_SIZES " | grep -q " $size " || die "$f: the size must be one of $APP_SIZES"
            ;;
    esac
done

# check the colors before running Inkscape
if [ -n "$names" ]; then
    svg_files=$(for name in $names; do echo "svg/$name.svg"; done)
    # shellcheck disable=SC2086
    awk -v mode=check -f palette.awk palette.txt $svg_files \
        || die "the SVG files must use only the LIGHT colors of palette.txt"
fi

INKSCAPE="${INKSCAPE:-inkscape}"
command -v "${INKSCAPE%% *}" >/dev/null 2>&1 \
    || die "${INKSCAPE%% *} is not found. Install Inkscape, or specify the command by INKSCAPE=/path/to/inkscape."

# remove the temporary files when an error occurs
trap 'rm -f light/*/*.tmp dark/*/*.tmp app/*/*.tmp' EXIT

# The SVG data is given from the standard input and the PNG data is written
# to the standard output, so that Inkscape does not need to access the files
# (e.g. Inkscape of snap cannot read the files in hidden directories, and
# it does not use the current directory of the shell).
export_options="--pipe --export-type=png --export-filename=- --export-background-opacity=0"

# export_png SIZE OUT
#   convert the SVG data of the standard input to the PNG file OUT
#   (INKSCAPE and export_options are split into words intentionally)
export_png()
{
    # shellcheck disable=SC2086
    $INKSCAPE $export_options -w "$1" -h "$1" > "$2.tmp" \
        && [ -s "$2.tmp" ] \
        || die "failed to create $2"
    mv "$2.tmp" "$2"
}

for name in $names; do
    for size in $SIZES; do
        mkdir -p "light/$size" "dark/$size"
        out="light/$size/$name.png"
        show "$INKSCAPE $export_options -w $size -h $size < svg/$name.svg > $out"
        export_png "$size" "$out" < "svg/$name.svg"

        out="dark/$size/$name.png"
        show "awk -v mode=dark -f palette.awk palette.txt svg/$name.svg | $INKSCAPE $export_options -w $size -h $size > $out"
        awk -v mode=dark -f palette.awk palette.txt "svg/$name.svg" | export_png "$size" "$out"
    done
done

for name in $app_names; do
    for size in $APP_SIZES; do
        src=$(app_source "$name" "$size")
        out="app/$size/$name.png"
        mkdir -p "app/$size"
        show "$INKSCAPE $export_options -w $size -h $size < $src > $out"
        export_png "$size" "$out" < "$src"
    done
done

update_lists
# shellcheck disable=SC2086
update_checksums $names $app_names
